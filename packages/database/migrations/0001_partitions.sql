-- ---------------------------------------------------------------------------
-- 8. Immutability enforcement (§6.15). BEFORE UPDATE OR DELETE triggers raise
--    IMMUTABLE_ROW, except two whitelisted deltas:
--      - observation.compacted false -> true (and capture_ref null-out), all else frozen.
--      - gateway_config_revision.status active -> superseded|rolled_back, all else frozen.
--    Partition DROP/DETACH is DDL, not DML, so these triggers never fire on retention.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION forbid_mutation() RETURNS trigger AS $$
BEGIN
	RAISE EXCEPTION 'IMMUTABLE_ROW: % on %', TG_OP, TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE OR REPLACE FUNCTION observation_guard_mutation() RETURNS trigger AS $$
DECLARE
	n observation := NEW;
BEGIN
	IF TG_OP = 'DELETE' THEN
		RAISE EXCEPTION 'IMMUTABLE_ROW: DELETE on observation';
	END IF;
	-- compacted may only flip false -> true
	IF NEW.compacted IS DISTINCT FROM OLD.compacted
	   AND NOT (OLD.compacted = false AND NEW.compacted = true) THEN
		RAISE EXCEPTION 'IMMUTABLE_ROW: illegal compacted transition on observation';
	END IF;
	-- capture_ref may only be nulled out (§13.6 step 3)
	IF NEW.capture_ref IS DISTINCT FROM OLD.capture_ref AND NEW.capture_ref IS NOT NULL THEN
		RAISE EXCEPTION 'IMMUTABLE_ROW: capture_ref may only be nulled on observation';
	END IF;
	-- no other column may change
	n.compacted := OLD.compacted;
	n.capture_ref := OLD.capture_ref;
	IF ROW(n.*) IS DISTINCT FROM ROW(OLD.*) THEN
		RAISE EXCEPTION 'IMMUTABLE_ROW: forbidden column change on observation';
	END IF;
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

CREATE OR REPLACE FUNCTION config_revision_guard_mutation() RETURNS trigger AS $$
DECLARE
	n gateway_config_revision := NEW;
BEGIN
	IF TG_OP = 'DELETE' THEN
		RAISE EXCEPTION 'IMMUTABLE_ROW: DELETE on gateway_config_revision';
	END IF;
	-- status may only go active -> superseded|rolled_back
	IF NEW.status IS DISTINCT FROM OLD.status
	   AND NOT (OLD.status = 'active' AND NEW.status IN ('superseded','rolled_back')) THEN
		RAISE EXCEPTION 'IMMUTABLE_ROW: illegal status transition on gateway_config_revision';
	END IF;
	n.status := OLD.status;
	IF ROW(n.*) IS DISTINCT FROM ROW(OLD.*) THEN
		RAISE EXCEPTION 'IMMUTABLE_ROW: forbidden column change on gateway_config_revision';
	END IF;
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

