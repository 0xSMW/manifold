-- ---------------------------------------------------------------------------
-- 6. Partition-maintenance helper (§6.13, §20.4). Creates a monthly RANGE partition
--    for a parent given any date within the target month. Idempotent.
--    The daily maintenance job calls this a month ahead; retention drops old partitions.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION create_month_partition(p_parent text, p_month date)
RETURNS text AS $$
DECLARE
	v_start date := date_trunc('month', p_month)::date;
	v_end   date := (date_trunc('month', p_month) + interval '1 month')::date;
	v_name  text := format('%s_%s', p_parent, to_char(v_start, 'YYYYMM'));
BEGIN
	EXECUTE format(
		'CREATE TABLE IF NOT EXISTS %I PARTITION OF %I FOR VALUES FROM (%L) TO (%L)',
		v_name, p_parent, v_start, v_end
	);
	RETURN v_name;
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

